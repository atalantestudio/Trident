	Scene2D::Scene2D(ref<Scene2DAsset> sceneAsset) :
		Scene({
			.dynamicVertexCount = sceneAsset->dynamicVertexPositionCount + sceneAsset->dynamicVertexTextureCoordinateCount,
			.dynamicIndexCount = sceneAsset->dynamicVertexPositionIndexCount + sceneAsset->dynamicVertexTextureCoordinateIndexCount
		}),
		asset(sceneAsset)
	{
		loadGeometries();
		loadEntityComponentMappings();
	}

	void Scene2D::loadGeometries() {
		const uint32 vertexComponentCount = static_cast<uint32>(asset->staticVertices.count() + dynamicVertexCount * 2);
		const uint64 vertexByteCount = asset->staticVertices.count() + dynamicVertexCount * sizeof(vec2<float32>);
		const uint64 indexByteCount = asset->staticTriangles.count() * 3 + dynamicIndexCount * sizeof(uint32);

		dataBuffer = sequence<uint8>(vertexByteCount + indexByteCount);
		geometries = sequence<Geometry2D>(asset->geometryAssets.count());
		hulls = sequence<Hull2D>(asset->hullCount);

		std::copy(asset->staticGeometryBuffer.begin(), asset->staticGeometryBuffer.end(), &dataBuffer[0]);

		uint8* dynamicDataBuffer = &dataBuffer[asset->staticGeometryBuffer.count()];
		uint64 offset = 0;

		range<uint32, uint32> vertexPositionComponentRange = {static_cast<uint32>(offset), 0};

		for (const ref<Geometry2DAsset> geometryAsset : asset->geometryAssets) {
			std::copy(geometryAsset->vertexPositionComponents.begin(), geometryAsset->vertexPositionComponents.end(), &pointer_cast<float32*>(dynamicDataBuffer)[offset]);

			offset += geometryAsset->vertexPositionComponents.count();
		}

		range<uint32, uint32> vertexTextureCoordinateComponentRange = {static_cast<uint32>(offset), 0};

		for (const ref<Geometry2DAsset> geometryAsset : asset->geometryAssets) {
			std::copy(geometryAsset->vertexTextureCoordinateComponents.begin(), geometryAsset->vertexTextureCoordinateComponents.end(), &pointer_cast<float32*>(dynamicDataBuffer)[offset]);

			offset += geometryAsset->vertexTextureCoordinateComponents.count();
		}

		range<uint32, uint32> vertexPositionIndexRange = {static_cast<uint32>(offset), 0};

		for (const ref<Geometry2DAsset> geometryAsset : asset->geometryAssets) {
			std::copy(geometryAsset->vertexPositionIndices.begin(), geometryAsset->vertexPositionIndices.end(), &pointer_cast<uint32*>(dynamicDataBuffer)[offset]);

			offset += geometryAsset->vertexPositionIndices.count();
		}

		uint32 geometryIndex = 0;
		uint32 hullIndex = 0;

		while (geometryIndex < geometries.count()) {
			const ref<Geometry2DAsset> geometryAsset = asset->geometryAssets[geometryIndex];

			vertexPositionComponentRange.count = static_cast<uint32>(geometryAsset->vertexPositionComponents.count());
			vertexTextureCoordinateComponentRange.count = static_cast<uint32>(geometryAsset->vertexTextureCoordinateComponents.count());
			vertexPositionIndexRange.count = static_cast<uint32>(geometryAsset->vertexPositionIndices.count());

			geometries[geometryIndex] = Geometry2D({
				.vertexPositionComponentRange = {vertexPositionComponentRange.offset, vertexPositionComponentRange.count},
				.vertexTextureCoordinateComponentRange = {vertexTextureCoordinateComponentRange.offset, vertexTextureCoordinateComponentRange.count},
				.indexRange = {vertexPositionIndexRange.offset - vertexComponentCount, vertexPositionIndexRange.count},
			});

			if (geometryAsset->flags & GeometryAssetFlags::HAS_HULL) {
				std::copy(geometryAsset->hullLineIndices.begin(), geometryAsset->hullLineIndices.end(), &pointer_cast<uint32*>(dynamicDataBuffer)[offset]);

				const view<vec2<float32>> vertices(pointer_cast<const vec2<float32>*>(&dynamicDataBuffer[vertexPositionComponentRange.offset * sizeof(float32)]), vertexPositionComponentRange.count / 2);

				geometries[geometryIndex].hullIndex = hullIndex;

				Hull2D& hull = hulls[hullIndex];
				hull = {
					.type = geometryAsset->hullType,
					.centroid = geometryAsset->hullCentroid,
					.radius = geometryAsset->hullRadius,
					.vertices = vertices,
					.lineIndexRange = {static_cast<uint32>(offset) - vertexComponentCount, static_cast<uint32>(geometryAsset->hullLineIndices.count())},
					.edges = {},
				};

				// TODO: Edges must be generated by the asset builder.
				if (hull.type == Hull2DType::POLYGON) {
					const uint32 edgeCount = static_cast<uint32>(geometryAsset->hullLineIndices.count() - 1);

					hull.edges = sequence<Edge2D>(edgeCount);

					uint32 edgeIndex = 0;

					while (edgeIndex < edgeCount) {
						hull.edges[edgeIndex] = {edgeIndex, (edgeIndex + 1) % edgeCount};

						edgeIndex += 1;
					}
				}

				offset += geometryAsset->hullLineIndices.count();

				hullIndex += 1;
			}

			vertexPositionComponentRange.offset += vertexPositionComponentRange.count;
			vertexTextureCoordinateComponentRange.offset += vertexTextureCoordinateComponentRange.count;
			vertexPositionIndexRange.offset += vertexPositionIndexRange.count;

			geometryIndex += 1;
		}
	}

	void Scene2D::loadEntityComponentMappings() {
		ecs.registerComponentPool<Geometry2DComponent>();

		// TODO(scene/2d/ecs/scene-components): Transform2DComponent for static meshes?
		ecs.registerComponentPool<RigidBody2DComponent>();

		// TODO(physics/2d/joint): Restore joints.
		// ecs.registerComponentPool<Joint2D>();

		// TODO(physics/2d/constraint): Restore constraints.
		// ecs.registerComponentPool<ref<Constraint2D>>();

		ecs.registerTagPool<DynamicEntityTag>();
		ecs.registerTagPool<StaticEntityTag>();

		Entity entity = 0;

		while (entity < asset->entityCount) {
			ecs.createEntity();

			entity += 1;
		}

		for (const EntityComponentMapping<Geometry2DComponent>& geometryMapping : asset->geometryMappings) {
			ecs.setComponent<Geometry2DComponent>(geometryMapping.entity, geometryMapping.component);
		}

		for (EntityComponentMapping<RigidBody2DComponent>& rigidBodyMapping : asset->rigidBodyMappings) {
			const Geometry2DComponent geometryComponent = ecs.getComponent<Geometry2DComponent>(rigidBodyMapping.entity);
			const Geometry2D& geometry = geometries[geometryComponent.geometryIndex];
			const Hull2D& hull = hulls[geometry.hullIndex];

			rigidBodyMapping.component.updateWorld(hull.centroid);

			ecs.setComponent<RigidBody2DComponent>(rigidBodyMapping.entity, rigidBodyMapping.component);

			// TODO(debug-only)
			if (rigidBodyMapping.component.inverseMass == 0.0_kg) {
				ecs.setTag<StaticEntityTag>(rigidBodyMapping.entity);
			}
			else {
				ecs.setTag<DynamicEntityTag>(rigidBodyMapping.entity);
			}
		}
	}

